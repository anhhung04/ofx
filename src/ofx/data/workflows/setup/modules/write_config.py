"""Write a proxychains configuration file under ~/.ofx/proxy."""

from __future__ import annotations

import os
import pathlib


def run(ctx):
    configured_dir = str(ctx.inputs.get("config_dir", "")).strip()
    if configured_dir:
        config_dir = pathlib.Path(configured_dir)
    else:
        config_dir = pathlib.Path(os.path.expanduser("~")) / ".ofx" / "proxy"
    config_dir.mkdir(parents=True, exist_ok=True)
    config_name = str(ctx.inputs.get("config_name", "")).strip() or "proxychains.conf"
    config_path = config_dir / config_name

    proxy_host = str(ctx.inputs.get("proxy_host", "127.0.0.1"))
    proxy_port = str(ctx.inputs.get("proxy_port", "9050"))
    proxy_type = str(ctx.inputs.get("proxy_type", "socks5"))
    chain_type = str(ctx.inputs.get("chain_type", "strict_chain"))
    chain_len = int(ctx.inputs.get("chain_len", 1))
    quiet = bool(ctx.inputs.get("quiet_mode", False))

    config = f"""# OFX Proxychains Configuration
# Generated by ofx flow run proxy-config
# Mode: {chain_type}

{"quiet_mode" if quiet else "#quiet_mode"}

# Chain type
{chain_type}

# Proxy DNS requests - no leak for DNS data
proxy_dns

# Dynamic chain length
chain_len = {chain_len}

# Remote DNS subnet
remote_dns_subnet 224

# Timeout (ms)
tcp_read_time_out 15000
tcp_connect_time_out 8000

[ProxyList]
{proxy_type} {proxy_host} {proxy_port}
"""

    config_path.write_text(config)
    config_path.chmod(0o600)
    ctx.add_outputs(
        config_path=str(config_path),
        proxy_list=f"{proxy_type}://{proxy_host}:{proxy_port}",
    )
    print(f"Proxychains config: {config_path}")
    print(f"Proxy: {proxy_type}://{proxy_host}:{proxy_port}")
    print(f"Chain: {chain_type} (length={chain_len})")
